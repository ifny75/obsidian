/**
 * Защита от молчаливого заведения пустой базы.
 *
 * # Что случилось
 *
 * Проект переименовали, путь к базе по умолчанию сменился с `obsidian.db` на
 * `valanium.db`. Сервер честно отработал сценарий первого запуска: файла нет —
 * значит, создаём новый. Пятнадцать аккаунтов остались в старом файле рядом, а
 * люди пришли на чистый сервер и стали регистрироваться заново.
 *
 * Ошибка была не в переименовании — переименовать надо было и файл. Ошибка в
 * том, что **сервер не отличает первый запуск от потерянной базы** и молчит в
 * обоих случаях. А молчание тут стоит дороже всего: пустая база выглядит
 * работающей, и узнают о потере не из журнала, а от людей.
 *
 * # Что делаем
 *
 * Если базы по указанному пути нет, но рядом лежит другая — отказываемся
 * стартовать и говорим, что нашли. Настоящий первый запуск от этого не
 * страдает: в пустом каталоге ничего рядом не лежит.
 *
 * Обойти можно переменной `VALANIUM_ALLOW_NEW_DB=true` — на случай, когда
 * вторая база оказалась рядом законно. Обход именно явный: сервер, который
 * можно уговорить молчать по умолчанию, ничем не лучше молчащего всегда.
 */
import { existsSync, readdirSync } from "node:fs";
import { basename, dirname } from "node:path";

/** Файлы SQLite, которые к базе мессенджера отношения не имеют. */
const NOT_OURS = /^(support|.*-wal|.*-shm)$/;

/**
 * Что мешает завести новую базу по этому пути.
 *
 * `null` — ничего не мешает: либо база уже есть, либо каталог пуст и это
 * действительно первый запуск.
 */
export function blockingNeighbour(path: string): string | null {
  if (path === ":memory:" || existsSync(path)) return null;

  const dir = dirname(path);
  if (!existsSync(dir)) return null;

  const ours = basename(path);
  const neighbours = readdirSync(dir).filter((name) => {
    if (!name.endsWith(".db") || name === ours) return false;
    return !NOT_OURS.test(name.slice(0, -3));
  });

  return neighbours.length > 0 ? (neighbours[0] as string) : null;
}

/**
 * Бросает, если по пути нет базы, а рядом лежит другая.
 *
 * Сообщение написано для человека в три часа ночи: что нашли, чем это,
 * скорее всего, является, и что делать.
 */
export function refuseToLoseDatabase(path: string): void {
  if (process.env["VALANIUM_ALLOW_NEW_DB"] === "true") return;

  const neighbour = blockingNeighbour(path);
  if (neighbour === null) return;

  throw new Error(
    `база ${basename(path)} не найдена, но рядом лежит ${neighbour}.\n`
    + "Похоже на переименование: путь сменился, а файл остался прежним.\n"
    + `Переименуйте файл, либо укажите VALANIUM_DB=${neighbour}.\n`
    + "Если пустая база нужна намеренно: VALANIUM_ALLOW_NEW_DB=true.\n"
    + "Сервер не стартует нарочно — пустая база выглядит работающей, "
    + "и о потере узнают не из журнала, а от людей.",
  );
}
