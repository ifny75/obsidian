//! Ступени размера для того, что уходит в шифротекст.
//!
//! # Зачем
//!
//! Длина шифротекста повторяет длину открытого текста, а длину видит сервер.
//! Добивка самого MLS выравнивает всё по 256 байт — этого хватает, чтобы
//! служебные сигналы и короткие реплики стали неразличимы, но фотография от
//! голосового по-прежнему отличается с точностью до четверти килобайта.
//!
//! Ступени убирают и это: размер округляется до ближайшей сверху, и внутри
//! ступени всё выглядит одинаково.
//!
//! # Почему ступени такие
//!
//! Густые внизу и редкие вверху. Обычное сообщение — это две-три сотни байт;
//! ровнять его до шестнадцати килобайт значило бы платить в полсотни раз
//! больше трафика за каждое «ок» и каждый сигнал «печатает» — на мобильном
//! это заметно и по батарее, и по счёту. Зато выше килобайта плотность уже не
//! нужна: там живут картинки и голос, и различать их по размеру ни к чему.
//!
//! Выше верхней ступени добивка идёт кратно 64 КиБ, а не до следующей степени
//! двойки: иначе снимок на 300 КиБ превратился бы в мегабайт и упёрся в предел
//! кадра.
//!
//! # Почему пробелами
//!
//! Добивка обязана быть незаметной для уже выпущенных клиентов, а они
//! разбирают тело как JSON. Пробелы после закрывающей скобки и `JSON.parse`, и
//! `JSONObject` пропускают молча — а любой другой символ сломал бы разбор. То
//! есть старый собеседник прочитает добитое сообщение как обычное, ничего не
//! зная про ступени.
//!
//! # Чего это не делает
//!
//! Не прячет факт отправки и её время: сервер по-прежнему видит «конверт
//! устройству X в момент T». Это работа sealed sender, и она в другом месте.
//! И не работает без толпы: пока пользователей единицы, ровнять размеры — всё
//! равно что прятать одну книгу в пустом шкафу.

/// Ступени в байтах. Ниже первой не спускаемся: всё мелкое становится 256.
const STEPS: [usize; 5] = [256, 1024, 4096, 16384, 65536];

/// Выше последней ступени округляем кратно этому.
const COARSE: usize = 64 * 1024;

/// Байт добивки. Пробел выбран не случайно — см. шапку.
const FILLER: u8 = b' ';

/// До какого размера добить тело.
pub fn target(length: usize) -> usize {
    for step in STEPS {
        if length <= step {
            return step;
        }
    }
    length.div_ceil(COARSE) * COARSE
}

/// Тело, добитое до ближайшей ступени сверху.
pub fn pad(body: &[u8]) -> Vec<u8> {
    let target = target(body.len());
    let mut out = Vec::with_capacity(target);
    out.extend_from_slice(body);
    out.resize(target, FILLER);
    out
}

/// Снимает добивку.
///
/// Срезаются только пробелы в конце — то есть ровно то, чем добивали. У самого
/// сообщения хвостовых пробелов нет: текст человека лежит внутри JSON, а не
/// снаружи, и его кавычки закрываются раньше.
pub fn strip(plain: &[u8]) -> &[u8] {
    let mut end = plain.len();
    while end > 0 && plain[end - 1] == FILLER {
        end -= 1;
    }
    &plain[..end]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn everything_small_becomes_the_same_size() {
        // Ради этого всё и делается: «да», «нет» и сигнал «печатает» обязаны
        // выглядеть на проводе одинаково.
        for body in ["да", "нет, давай завтра", "\u{2063}OBSCTL1:{\"typing\":true}"] {
            assert_eq!(pad(body.as_bytes()).len(), 256, "не сошлось на {body:?}");
        }
    }

    #[test]
    fn steps_are_dense_at_the_bottom_and_sparse_above() {
        assert_eq!(target(1), 256);
        assert_eq!(target(256), 256);
        assert_eq!(target(257), 1024);
        assert_eq!(target(4096), 4096);
        assert_eq!(target(4097), 16384);
        assert_eq!(target(65536), 65536);

        // Выше последней ступени — кратно 64 КиБ, а не до мегабайта: снимок на
        // 300 КиБ иначе упёрся бы в предел кадра.
        assert_eq!(target(65537), 128 * 1024);
        assert_eq!(target(300 * 1024), 320 * 1024);
        assert!(target(700 * 1024) < 1024 * 1024, "добивка не должна выносить за предел кадра");
    }

    #[test]
    fn padding_comes_off_whole() {
        for body in ["да", "\u{2063}OBS1:{\"v\":1,\"type\":\"text\",\"text\":\"привет\"}"] {
            let padded = pad(body.as_bytes());
            assert!(padded.len() > body.len());
            assert_eq!(strip(&padded), body.as_bytes(), "не восстановилось {body:?}");
        }
    }

    #[test]
    fn a_message_that_never_was_padded_survives() {
        // Сообщение от старого клиента добивки не несёт — снимать нечего.
        let body = "\u{2063}OBS1:{\"v\":1}";
        assert_eq!(strip(body.as_bytes()), body.as_bytes());
        assert_eq!(strip(b""), b"");
    }

    #[test]
    fn the_users_own_spaces_are_safe() {
        /*
          Текст человека лежит внутри JSON, в кавычках, поэтому хвостовые
          пробелы в нём добивкой не считаются и не срезаются. Проверяем именно
          это: снаружи срезается, внутри остаётся.
        */
        let body = "\u{2063}OBS1:{\"v\":1,\"text\":\"привет   \"}";
        let padded = pad(body.as_bytes());
        let back = strip(&padded);
        assert_eq!(back, body.as_bytes());
        assert!(
            String::from_utf8_lossy(back).contains("привет   "),
            "пробелы человека обязаны уцелеть",
        );
    }

    #[test]
    fn a_body_of_exactly_a_step_is_not_grown() {
        // Иначе каждое ровное тело перепрыгивало бы на ступень выше и мы
        // платили бы вчетверо ни за что.
        let body = vec![b'x'; 1024];
        assert_eq!(pad(&body).len(), 1024);
    }
}
